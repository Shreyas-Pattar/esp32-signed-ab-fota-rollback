#!/usr/bin/env python3
"""
Host tool for the ESP32 FOTA demo.

  python fota_tool.py keygen
  python fota_tool.py send fw_v2_good.bin --version 2 --port COM5
  python fota_tool.py send fw_v3_bad.bin  --version 3 --port COM5 --tamper
  python fota_tool.py send fw_v3_bad.bin  --version 3 --port COM5 --badsig

Needs:  pip install pyserial cryptography
Close the Arduino Serial Monitor before running 'send' (it holds the COM port).
"""
import argparse
import hashlib
import struct
import sys
import time

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

PRIVATE_KEY_FILE = "fota_private.pem"
PUBLIC_HEADER_FILE = "public_key.h"
CHUNK = 1024


def keygen():
    key = ec.generate_private_key(ec.SECP256R1())
    with open(PRIVATE_KEY_FILE, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM,
                                  serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    pem = key.public_key().public_bytes(
        serialization.Encoding.PEM,
        serialization.PublicFormat.SubjectPublicKeyInfo).decode().strip().splitlines()
    with open(PUBLIC_HEADER_FILE, "w") as f:
        f.write("// Generated by fota_tool.py keygen (public key only)\n")
        f.write("#pragma once\n")
        f.write("static const char FOTA_PUBLIC_KEY_PEM[] =\n")
        for line in pem:
            f.write('    "%s\\n"\n' % line)
        f.write(";\n")
    print("Wrote %s (KEEP SECRET, never upload it) and %s (copy into the sketch folder)."
          % (PRIVATE_KEY_FILE, PUBLIC_HEADER_FILE))


def make_message(version, size, digest):
    # Must match Verify_Signature() in the sketch: version(LE) | size(LE) | sha256
    return struct.pack("<II", version, size) + digest


def sign(key, version, size, digest):
    return key.sign(make_message(version, size, digest), ec.ECDSA(hashes.SHA256()))


def send(args):
    import serial  # pyserial

    img = open(args.bin, "rb").read()
    digest = hashlib.sha256(img).digest()

    if args.badsig:
        key = ec.generate_private_key(ec.SECP256R1())  # a key the device does not trust
    else:
        key = serialization.load_pem_private_key(open(PRIVATE_KEY_FILE, "rb").read(), None)
    sig = sign(key, args.version, len(img), digest)

    payload = bytearray(img)
    if args.tamper:
        payload[len(payload) // 2] ^= 0xFF  # corrupt the data AFTER hashing/signing

    print("Image: %s  size=%d  version=%d  sha256=%s" % (args.bin, len(img), args.version, digest.hex()))
    print("Mode: %s" % ("TAMPERED image" if args.tamper else "BAD signature" if args.badsig else "normal"))

    ser = serial.Serial()
    ser.port = args.port
    ser.baudrate = 115200
    ser.timeout = 5
    ser.dtr = False
    ser.rts = False
    ser.open()
    time.sleep(3)              # the board may reset when the port opens
    ser.reset_input_buffer()

    header = (b"FOTA" + struct.pack("<II", args.version, len(img)) + digest +
              struct.pack("<H", len(sig)) + sig)
    ser.write(header)

    ser.timeout = 20           # flash erase can take a few seconds
    resp = ser.read(1)
    if resp != b"K":
        time.sleep(1)
        print("Device REJECTED the update header:", (resp + ser.read(300)).decode(errors="replace").strip())
        return 1

    ser.timeout = 5
    sent = 0
    last_pct = -1
    while sent < len(payload):
        chunk = bytes(payload[sent:sent + CHUNK])
        ser.write(chunk)
        ack = ser.read(1)
        if ack != b"A":
            print("\nTransfer failed:", (ack + ser.read(300)).decode(errors="replace").strip())
            return 1
        sent += len(chunk)
        pct = sent * 100 // len(payload)
        if pct // 10 != last_pct // 10:
            print("  %d%%" % pct)
            last_pct = pct

    ser.timeout = 15
    final = ser.read(1)
    if final != b"D":
        time.sleep(1)
        print("Device REJECTED the image:", (final + ser.read(300)).decode(errors="replace").strip())
        return 1

    print("Device accepted the image. Device output follows:\n" + "-" * 60)
    end = time.time() + args.watch
    ser.timeout = 0.5
    while time.time() < end:
        data = ser.read(512)
        if data:
            sys.stdout.write(data.decode(errors="replace"))
            sys.stdout.flush()
    return 0


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("keygen")
    s = sub.add_parser("send")
    s.add_argument("bin")
    s.add_argument("--version", type=int, required=True)
    s.add_argument("--port", required=True)
    s.add_argument("--tamper", action="store_true")
    s.add_argument("--badsig", action="store_true")
    s.add_argument("--watch", type=int, default=25, help="seconds of device output to show")
    args = p.parse_args()
    if args.cmd == "keygen":
        keygen()
        return 0
    return send(args)


if __name__ == "__main__":
    sys.exit(main())